#!/usr/bin/env python3
"""THE COVERAGE REGISTER: everything the annual town reports print, and how much of it is data.

    python3 scripts/build_annual_report_coverage.py           # write the page and the two CSVs
    python3 scripts/build_annual_report_coverage.py --check   # fail if any of them is stale

Writes:
  notes/reference/EXTRACTION-GAPS.md               the page
  sources/data/annual-report-coverage.csv          one row per edition (67)
  sources/data/annual-report-coverage-datasets.csv one row per dataset holding report rows

Step 1 of notes/PLAN-EVERYTHING-IN-THE-REPORTS.md. TJ, 1 November 2026: *"i want all the
datasets found in the annual reports to get into the database, very easily searchable and
analyzable."*

WHY THIS EXISTS. `EXTRACTION-GAPS.md` said "Generated by scripts/build_extraction_gaps.py"
and nothing generated it. That script merges `extraction` rows into money-gaps.csv and never
wrote the page, so the page was a snapshot of 7 September 2026 wearing a generated label:
sixteen reports instead of 67, and two families "never extracted" that had been datasets for
weeks. A label saying "generated" is a claim, and a claim nobody checks is how this archive's
defects are made. This script is that claim made true, and it is in check_generated.py.

WHAT IS COUNTED, AND WHERE EACH NUMBER COMES FROM -- nothing on the page is typed:

  pages            the `===PAGE N===` markers in each report's text file (they equal the PDF's
                   own page count for all 68 files, checked 1 November 2026)
  financial pages  sources/data/annual-report-pages.csv, the page map, with its `state`
  1959-2010        sources/data/report-tables/<edition>/tables.csv is every table Textract
                   found; map.csv is the decision taken on each, BY EYE: a `dataset`, or empty
                   with the reason in `note`. The script REFUSES if the two disagree on which
                   tables exist, because then "every table has a decision" would be false.
  FY2011-FY2025    sources/data/annual-report-catalogue.csv, the end-to-end survey. It has no
                   table-to-dataset mapping (step 4 of the plan builds one), so the page says
                   so rather than inventing one. What it does give, LABELLED AS A PAGE-LEVEL
                   PROXY: how many catalogued tables sit on a page some dataset has rows from.
  datasets         every top-level sources/data/*.csv, each row attributed to an edition by its
                   `edition` column, else by a document column naming an annual town report,
                   else by the year column named in YEAR_COLUMN. A dataset is "fed by the
                   reports" when at least one row attributes. That is observed, row by row.
  in the database  whether sources/data/lunenburg.db has a table of that name, and its rows.
  checked / ...    the dataset's own `status` column, split, never summed across.
  lists            EMPTY FOR NOW. Step 3 (a list survey) fills `lists_found` and
                   `lists_in_dataset`; until then the columns exist and say nothing.
"""
import argparse
import collections
import csv
import glob
import io
import os
import re
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import report_year  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'sources', 'data')
TABLES = os.path.join(DATA, 'report-tables')
DB = os.path.join(DATA, 'lunenburg.db')
OUT_MD = os.path.join(ROOT, 'notes', 'reference', 'EXTRACTION-GAPS.md')
OUT_EDITIONS = os.path.join(DATA, 'annual-report-coverage.csv')
OUT_DATASETS = os.path.join(DATA, 'annual-report-coverage-datasets.csv')
SELF = {os.path.basename(OUT_EDITIONS)[:-4], os.path.basename(OUT_DATASETS)[:-4]}

# Columns that can name the document a row was read from.
DOC_COLUMNS = ('document', 'source', 'pdf', 'doc', 'file', 'report')

# Datasets with no edition and no document column whose rows are still one report each,
# and the column that says which. `fy` here is the REPORT's year -- verified for each
# before it was listed, because elsewhere `fy` is usually the year a figure is about.
YEAR_COLUMN = {
    'report-index': 'fy',        # extract_report_index.py: one contents page per FY report
    'report-signatures': 'fy',   # extract_report_signatures.py: signatures in that report
}

# Files that mention the annual reports but are ABOUT THE DOCUMENTS OR OUR READING, not data
# the reports print. Each is named with its reason; they are listed on the page separately so
# nothing vanishes.
ABOUT_THE_READING = {
    'annual-report-catalogue': 'the survey of what tables exist; this page counts it',
    'annual-report-pages': 'the financial page map; this page counts it',
    'annual-report-survey': 'per-page character and money counts from the FY survey',
    'extraction-plan': 'what was planned to be read, and its state',
    'dataset-provenance': 'which dataset holds rows from which edition (generated)',
    'document-defects': 'defects in the documents themselves, as found',
    'page-blocked': 'pages closed without a reading, each with the document that would settle it',
    'report-anomalies': 'oddities noticed while reading (announced but absent, and so on)',
    'stabilization-pages': 'the page map for the stabilization extractor',
    'thread-callouts': 'meeting-thread callouts; one cites an annual report, none is report data',
}
REGISTER_SUFFIXES = ('-refused', '-unreconciled', '-unfooted')
REGISTERS = {'receivables-reconciliation'}

STATUSES = ('checked', 'check failed', 'no check')


# --------------------------------------------------------------------------- reading

def read_csv(path):
    with open(path, newline='', encoding='utf-8') as fh:
        return list(csv.DictReader(fh))


def base_edition(key):
    """FY2016-addendum is part of the FY2016 edition: 67 editions, 68 files."""
    return key.replace('-addendum', '')


def editions():
    """{edition: {'era', 'year', 'documents': [...], 'pages': int}} from every mirror's index."""
    out = {}
    for path in sorted(glob.glob(os.path.join(ROOT, 'sources', '*', 'index.csv'))):
        for r in read_csv(path):
            local = r.get('local') or ''
            if 'annual-town-report' not in local or not local.endswith('.pdf'):
                continue
            e = report_year.report_edition(local)
            if not e:
                continue
            key = base_edition(e.key)
            text = os.path.join(ROOT, r.get('text') or '')
            if not r.get('text') or not os.path.exists(text):
                raise SystemExit('no text file for %s (index says %r); its pages cannot be '
                                 'counted. Run sync_archive.py --pull?' % (local, r.get('text')))
            with open(text, encoding='utf-8', errors='replace') as fh:
                marks = [int(n) for n in re.findall(r'^===PAGE (\d+)===', fh.read(), re.M)]
            if not marks:
                raise SystemExit('%s has no ===PAGE N=== markers' % text)
            d = out.setdefault(key, {'era': e.basis, 'year': e.year, 'documents': [],
                                     'pages': 0})
            if os.path.basename(local) in d['documents']:
                continue
            d['documents'].append(os.path.basename(local))
            d['pages'] += max(marks)
    if not out:
        raise SystemExit('no annual town reports in any sources/*/index.csv')
    return out


def edition_of(row, name, known):
    """The edition a dataset row was read from, or '' when it does not say."""
    ed = (row.get('edition') or '').strip()
    if ed:
        ed = base_edition(ed)
        if ed in known:
            return ed
        if ('FY' + ed) in known and known['FY' + ed]['era'] == 'fiscal':
            return 'FY' + ed
        return '?' + ed
    for c in DOC_COLUMNS:
        v = row.get(c) or ''
        if 'annual-town-report' in v:
            e = report_year.report_edition(v.split()[0] if ' ' in v.strip() else v)
            if e:
                return base_edition(e.key)
    col = YEAR_COLUMN.get(name)
    if col and (row.get(col) or '').strip():
        return 'FY%s' % row[col].strip()
    return ''


def role_of(name):
    if name in ABOUT_THE_READING:
        return 'about the reading'
    if name in REGISTERS or name.endswith(REGISTER_SUFFIXES):
        return 'register'
    return 'data'


def scan_datasets(known):
    """Every top-level CSV with at least one row read from an annual report."""
    out = {}
    for path in sorted(glob.glob(os.path.join(DATA, '*.csv'))):
        name = os.path.basename(path)[:-4]
        if name in SELF:
            continue
        rows = read_csv(path)
        if not rows:
            continue
        cols = rows[0].keys()
        if not ('edition' in cols or name in YEAR_COLUMN
                or any(c in cols for c in DOC_COLUMNS)):
            continue
        by_ed = collections.Counter()
        status = collections.defaultdict(collections.Counter)
        pages = collections.defaultdict(set)
        unknown = collections.Counter()
        for r in rows:
            ed = edition_of(r, name, known)
            if not ed:
                continue
            if ed.startswith('?'):
                unknown[ed[1:]] += 1
                continue
            by_ed[ed] += 1
            era = known[ed]['era']
            st = (r.get('status') or '').strip()
            if 'status' in cols:
                status[era][st if st in STATUSES else 'other'] += 1
            for p in re.findall(r'\d+', str(r.get('page') or r.get('pages') or '')):
                pages[ed].add(int(p))
        if not by_ed and not unknown:
            continue
        out[name] = {'rows': len(rows), 'by_edition': by_ed, 'status': status,
                     'has_status': 'status' in cols, 'pages': pages, 'unknown': unknown,
                     'role': role_of(name)}
    return out


def calendar_tables(known):
    """{edition: [map rows]} for every 1959-2010 edition, refusing if tables and map disagree."""
    out = {}
    for ed, d in known.items():
        if d['era'] != 'calendar':
            continue
        folder = os.path.join(TABLES, ed)
        tpath, mpath = os.path.join(folder, 'tables.csv'), os.path.join(folder, 'map.csv')
        if not (os.path.exists(tpath) and os.path.exists(mpath)):
            raise SystemExit('%s has no tables.csv/map.csv in %s' % (ed, folder))
        found = {(r['page'], r['table']) for r in read_csv(tpath)}
        mapped = read_csv(mpath)
        keys = {(r['page'], r['table']) for r in mapped}
        if found != keys:
            raise SystemExit(
                '%s: tables.csv and map.csv disagree -- %d table(s) found and not decided, '
                '%d decided and not found. "Every table has a decision" would be false.'
                % (ed, len(found - keys), len(keys - found)))
        out[ed] = mapped
    folders = {os.path.basename(p.rstrip('/')) for p in glob.glob(os.path.join(TABLES, '*/'))}
    stray = sorted(folders - set(out))
    if stray:
        raise SystemExit('report-tables/ holds edition folder(s) with no report in the index: %s'
                         % ', '.join(stray))
    return out


def db_tables():
    if not os.path.exists(DB):
        raise SystemExit('%s missing. Run: python3 scripts/build_db.py' % os.path.relpath(DB, ROOT))
    c = sqlite3.connect('file:%s?mode=ro' % DB, uri=True)
    out = {}
    for (t,) in c.execute("SELECT name FROM sqlite_master WHERE type IN ('table','view')"):
        out[t] = c.execute('SELECT COUNT(*) FROM "%s"' % t).fetchone()[0]
    c.close()
    return out


# --------------------------------------------------------------------------- computing

def compute():
    known = editions()
    cal = calendar_tables(known)
    datasets = scan_datasets(known)
    intable = db_tables()

    def in_db(name):
        return name.replace('-', '_') in intable

    # the financial page map, per edition
    fin = collections.defaultdict(collections.Counter)
    for r in read_csv(os.path.join(DATA, 'annual-report-pages.csv')):
        e = report_year.report_edition(r.get('document') or '')
        if not e:
            raise SystemExit('annual-report-pages.csv row with no edition: %r' % r)
        fin[base_edition(e.key)][r.get('state') or ''] += 1

    # the FY catalogue
    catalogue = collections.defaultdict(list)
    for r in read_csv(os.path.join(DATA, 'annual-report-catalogue.csv')):
        ed = base_edition(r.get('edition') or '')
        if ed in known and known[ed]['era'] == 'fiscal':
            catalogue[ed].append(r)

    data_names = sorted(n for n, d in datasets.items() if d['role'] == 'data')
    read_pages = collections.defaultdict(set)      # edition -> pages any DATA dataset reads
    for n in data_names:
        for ed, ps in datasets[n]['pages'].items():
            read_pages[ed] |= ps

    # calendar map: tables per dataset
    map_count = collections.Counter()
    for ed, rows in cal.items():
        for r in rows:
            if r['dataset']:
                map_count[r['dataset']] += 1

    order = sorted(known, key=lambda k: (known[k]['era'] != 'calendar', known[k]['year']))
    ed_rows = []
    for ed in order:
        d = known[ed]
        fed = sorted(n for n in data_names if datasets[n]['by_edition'].get(ed))
        row = collections.OrderedDict()
        row['edition'] = ed
        row['era'] = d['era']
        row['documents'] = ';'.join(sorted(d['documents']))
        row['pages'] = d['pages']
        row['financial_pages'] = sum(fin[ed].values())
        row['financial_proven'] = fin[ed].get('proven', 0)
        row['financial_blocked'] = fin[ed].get('blocked', 0)
        if d['era'] == 'calendar':
            m = cal[ed]
            landed = [r for r in m if r['dataset']]
            row['tables_found'] = len(m)
            row['tables_decided'] = len(m)
            row['tables_in_dataset'] = len(landed)
            row['tables_not_landed'] = len(m) - len(landed)
            row['tables_in_db'] = sum(1 for r in landed if in_db(r['dataset']))
            row['catalogued_on_a_read_page'] = ''
        else:
            cat = catalogue.get(ed, [])
            on = 0
            for r in cat:
                ps = {int(p) for p in re.findall(r'\d+', r.get('pages') or '')}
                if ps & read_pages.get(ed, set()):
                    on += 1
            row['tables_found'] = len(cat)
            row['tables_decided'] = ''          # step 4 sorts these; nothing has yet
            row['tables_in_dataset'] = ''
            row['tables_not_landed'] = ''
            row['tables_in_db'] = ''
            row['catalogued_on_a_read_page'] = on
        row['datasets_fed'] = len(fed)
        row['datasets_fed_names'] = ';'.join(fed)
        row['datasets_not_in_db'] = ';'.join(n for n in fed if not in_db(n))
        row['lists_found'] = ''                 # step 3: the list survey fills these
        row['lists_in_dataset'] = ''
        ed_rows.append(row)

    ds_rows = []
    for n in sorted(datasets, key=lambda n: (-sum(datasets[n]['by_edition'].values()), n)):
        d = datasets[n]
        row = collections.OrderedDict()
        row['dataset'] = n
        row['role'] = d['role']
        row['table'] = n.replace('-', '_')
        row['in_db'] = 'yes' if in_db(n) else 'no'
        row['db_rows'] = intable.get(n.replace('-', '_'), '')
        row['csv_rows'] = d['rows']
        row['rows_from_reports'] = sum(d['by_edition'].values())
        row['calendar_editions'] = sum(1 for e in d['by_edition'] if known[e]['era'] == 'calendar')
        row['fiscal_editions'] = sum(1 for e in d['by_edition'] if known[e]['era'] == 'fiscal')
        row['calendar_tables_mapped'] = map_count.get(n, 0)
        for era, tag in (('calendar', 'cal'), ('fiscal', 'fy')):
            s = d['status'].get(era, collections.Counter())
            for st, col in (('checked', 'checked'), ('check failed', 'failed'),
                            ('no check', 'nocheck')):
                row['%s_%s' % (tag, col)] = s.get(st, 0) if d['has_status'] else ''
            row['%s_other_status' % tag] = s.get('other', 0) if d['has_status'] else ''
        row['unattributed_editions'] = ';'.join('%s:%d' % kv for kv in sorted(d['unknown'].items()))
        ds_rows.append(row)

    # a dataset the calendar map lands tables in must exist as a file with rows
    missing = sorted(set(map_count) - set(datasets))
    if missing:
        raise SystemExit('map.csv lands tables in dataset(s) with no report rows on disk: %s'
                         % ', '.join(missing))
    return known, ed_rows, ds_rows, cal


# --------------------------------------------------------------------------- writing

def to_csv(rows):
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=list(rows[0].keys()), lineterminator='\n')
    w.writeheader()
    w.writerows(rows)
    return buf.getvalue()


def n(x):
    return '{:,}'.format(x)


def render(known, ed_rows, ds_rows, cal):
    cal_eds = [r for r in ed_rows if r['era'] == 'calendar']
    fy_eds = [r for r in ed_rows if r['era'] == 'fiscal']
    s = lambda rows, k: sum(int(r[k] or 0) for r in rows)
    found_c, landed_c = s(cal_eds, 'tables_found'), s(cal_eds, 'tables_in_dataset')
    notl_c, indb_c = s(cal_eds, 'tables_not_landed'), s(cal_eds, 'tables_in_db')
    found_f, onread_f = s(fy_eds, 'tables_found'), s(fy_eds, 'catalogued_on_a_read_page')
    data = [r for r in ds_rows if r['role'] == 'data']
    data_out = [r for r in data if r['in_db'] == 'no']
    regs = [r for r in ds_rows if r['role'] == 'register']
    about = [r for r in ds_rows if r['role'] == 'about the reading']
    pages_all = s(ed_rows, 'pages')
    cy0, cy1 = cal_eds[0]['edition'], cal_eds[-1]['edition']
    fy0, fy1 = fy_eds[0]['edition'], fy_eds[-1]['edition']

    # why the calendar tables were not landed: the note's own first clause, grouped
    reasons = collections.Counter()
    for rows in cal.values():
        for r in rows:
            if not r['dataset']:
                reasons[(r['name'] or '(unnamed)').split(':')[0].strip()[:70]] += 1

    L = []
    w = L.append
    w('# What the annual reports print, and how much of it is data')
    w('')
    w('**Generated by `scripts/build_annual_report_coverage.py`. Do not edit.** '
      'Checked by `check_generated.py`. One row per edition: '
      '`sources/data/annual-report-coverage.csv`; one per dataset: '
      '`sources/data/annual-report-coverage-datasets.csv`.')
    w('')
    w('## What is not yet data')
    w('')
    w('| | %s-%s (%d editions, Textract) | %s-%s (%d editions) |' % (
        cy0, cy1, len(cal_eds), fy0, fy1, len(fy_eds)))
    w('|---|---:|---:|')
    w('| pages | %s | %s |' % (n(s(cal_eds, 'pages')), n(s(fy_eds, 'pages'))))
    w('| tables found | %s | %s catalogued |' % (n(found_c), n(found_f)))
    w('| tables with a decision | %s | **not sorted yet** (step 4) |' % n(s(cal_eds, 'tables_decided')))
    w('| tables in a dataset | %s | not known at table grain |' % n(landed_c))
    w('| tables whose dataset is in the database | %s | not known at table grain |' % n(indb_c))
    w('| **tables looked at and NOT in a dataset** | **%s** | **%s** catalogued, unsorted |'
      % (n(notl_c), n(found_f)))
    w('| catalogued tables on a page some dataset reads (page-level proxy) | | %s of %s |'
      % (n(onread_f), n(found_f)))
    w('| named lists found (officers, staff, licences ...) | not surveyed yet (step 3) '
      '| not surveyed yet (step 3) |')
    w('')
    w('- **%s of %s tables in the %s-%s editions are not in any dataset.** Each was looked at by '
      'eye and its reason is in that edition\'s `map.csv` `note`, beginning `NOT LANDED`.'
      % (n(notl_c), n(found_c), cy0, cy1))
    w('- **None of the %s tables catalogued in %s-%s has been sorted** into a repeat of a table '
      'already read, prose, or a real gap. %s of them sit on a page no dataset has a row from, '
      'and those are the first place to look.' % (n(found_f), fy0, fy1, n(found_f - onread_f)))
    if data_out:
        w('- **%d of %d datasets holding report rows are not in the database:** %s.' % (
            len(data_out), len(data),
            ', '.join('`%s` (%s rows)' % (r['dataset'], n(r['rows_from_reports']))
                      for r in data_out)))
    else:
        w('- **All %d datasets holding report rows are in the database.**' % len(data))
    w('- **Lists are not counted yet.** Most years print officers and staff as running text, '
      'not tables, and every survey so far looked for tables. `lists_found` and '
      '`lists_in_dataset` are empty in the edition CSV until the list survey (step 3) runs.')
    w('')
    w('The proxy row is page grain, not table grain: a catalogued table counts if ANY dataset '
      'holds a row from ANY of its pages, so it is an upper bound on what has been read, '
      'never a count of tables read.')
    w('')

    w('## Every dataset the reports feed, and whether its figures are checked')
    w('')
    w('`checked`: the rows tie to a total or identity the page itself prints. `check failed`: '
      'they do not. `no check`: the page prints nothing to check against. Split, never summed '
      '-- CLAUDE.md, *The annual town reports*. A dash means the dataset has no `status` column.')
    w('')
    w('| dataset | in db | rows from reports | editions (cal / FY) | checked | check failed | no check |')
    w('|---|---|---:|---:|---:|---:|---:|')
    tot = collections.Counter()
    for r in data:
        hs = r['cal_checked'] != ''
        vals = []
        for col in ('checked', 'failed', 'nocheck'):
            if hs:
                v = int(r['cal_' + col]) + int(r['fy_' + col])
                tot[col] += v
                vals.append(n(v))
            else:
                vals.append('-')
        tot['rows'] += r['rows_from_reports']
        flag = '' if r['in_db'] == 'yes' else ' **NOT IN DB**'
        w('| `%s` | %s%s | %s | %d / %d | %s |' % (
            r['dataset'], r['in_db'], flag, n(r['rows_from_reports']),
            r['calendar_editions'], r['fiscal_editions'], ' | '.join(vals)))
    w('| **total** | | **%s** | | **%s** | **%s** | **%s** |' % (
        n(tot['rows']), n(tot['checked']), n(tot['failed']), n(tot['nocheck'])))
    w('')
    unat = [r for r in ds_rows if r['unattributed_editions']]
    if unat:
        w('Rows naming an edition this archive does not hold (left out of the counts above): '
          + '; '.join('`%s` %s' % (r['dataset'], r['unattributed_editions']) for r in unat) + '.')
        w('')

    w('## Registers and files about the reading')
    w('')
    w('Not data the reports print, and listed so that nothing disappears. A register records '
      'what was refused and why.')
    w('')
    w('| file | kind | rows from reports | in db |')
    w('|---|---|---:|---|')
    for r in regs + about:
        w('| `%s` | %s | %s | %s |' % (r['dataset'], r['role'], n(r['rows_from_reports']),
                                     r['in_db']))
    w('')

    w('## Edition by edition')
    w('')
    w('| edition | pages | financial pages (proven / blocked) | tables found | in a dataset '
      '| not landed | dataset in db | datasets fed | not in db |')
    w('|---|---:|---:|---:|---:|---:|---:|---:|---|')
    for r in ed_rows:
        cal_ = r['era'] == 'calendar'
        w('| %s | %s | %s (%s / %s) | %s | %s | %s | %s | %s | %s |' % (
            r['edition'], n(r['pages']), r['financial_pages'], r['financial_proven'],
            r['financial_blocked'],
            n(r['tables_found']) + ('' if cal_ else ' catalogued'),
            n(r['tables_in_dataset']) if cal_ else '-',
            n(r['tables_not_landed']) if cal_ else '-',
            n(r['tables_in_db']) if cal_ else '-',
            r['datasets_fed'],
            ', '.join('`%s`' % x for x in r['datasets_not_in_db'].split(';') if x) or ''))
    w('')

    w('## Why %s-%s tables were not landed, by what the map calls them' % (cy0, cy1))
    w('')
    w('The `name` the map gives each NOT LANDED table, grouped; the reason for each table is '
      'in its edition\'s `map.csv`. The most frequent:')
    w('')
    w('| what the table is | tables |')
    w('|---|---:|')
    for k, v in reasons.most_common(25):
        w('| %s | %d |' % (k.replace('|', '/'), v))
    rest = sum(reasons.values()) - sum(v for _, v in reasons.most_common(25))
    if rest:
        w('| everything else | %d |' % rest)
    w('')

    w('## How this is counted')
    w('')
    w('- **Pages** are the `===PAGE N===` markers in each report\'s text file, %s across %d '
      'editions; FY2016\'s addendum is counted with FY2016.' % (n(pages_all), len(ed_rows)))
    w('- **%s-%s:** `report-tables/<edition>/tables.csv` is every table Textract found on the '
      'pages it was asked to read; `map.csv` is the decision on each. The generator refuses to '
      'write if the two disagree about which tables exist. Textract read tables only on pages '
      'with money on them, so a table on a page with none is not in either file.' % (cy0, cy1))
    w('- **%s-%s:** `annual-report-catalogue.csv` is the end-to-end survey. It records what '
      'exists, and nothing maps its entries to datasets yet.' % (fy0, fy1))
    w('- **A dataset is fed by the reports** when at least one of its rows names an edition, '
      'by its `edition` column or a document column naming an annual town report. '
      '`report-filing` is DERIVED from the contents pages and names no edition, so it is '
      'not counted here; it is in the database.')
    w('- **In the database** means `sources/data/lunenburg.db` has a table of that name. '
      '`build_db.py` refuses to build if a `report-*.csv` is neither loaded nor excluded '
      'with a reason.')
    w('- **A matcher that finds nothing is a statement about the matcher** (rule 13c). A '
      'table counted as not landed was looked at and declined by eye, with the reason '
      'written down; a catalogued FY table counted as unsorted has simply not been looked at '
      'yet, and is not evidence that it is unread.')
    w('')
    return '\n'.join(L) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    known, ed_rows, ds_rows, cal = compute()
    outs = {OUT_MD: render(known, ed_rows, ds_rows, cal),
            OUT_EDITIONS: to_csv(ed_rows),
            OUT_DATASETS: to_csv(ds_rows)}
    stale = []
    for path, text in outs.items():
        rel = os.path.relpath(path, ROOT)
        if args.check:
            cur = open(path, encoding='utf-8').read() if os.path.exists(path) else None
            if cur != text:
                stale.append(rel)
        else:
            with open(path + '.tmp', 'w', encoding='utf-8', newline='') as fh:
                fh.write(text)
            os.replace(path + '.tmp', path)
            print('wrote %s' % rel)
    if stale:
        raise SystemExit('STALE: %s -- run python3 scripts/build_annual_report_coverage.py'
                         % ', '.join(stale))
    if args.check:
        print('annual-report coverage: up to date (%d editions, %d datasets)'
              % (len(ed_rows), len(ds_rows)))


if __name__ == '__main__':
    main()
