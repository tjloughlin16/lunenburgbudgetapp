#!/usr/bin/env python3
"""Handoff docs: the index, and a check that stops them going stale.

    python3 scripts/check_handoffs.py           # one line per live handoff, oldest first
    python3 scripts/check_handoffs.py --check   # exit 1, naming each failure

THE CONVENTION, CLAUDE.md "Picking up mid-stream" (status blocks added to every handoff on
4 November 2026, commit 7a11394b3): a handoff's state is in its first lines, not its prose.
Every `notes/HANDOFF-*.md` -- and any `notes/PLAN-*.md` that carries one -- opens with a
block between `---` lines:

    live, in notes/:            status: open | parked | reference
                                updated: YYYY-MM-DD
                                next: ...
                                waiting_on: ...        (required when parked)
    retired, notes/handoffs-done/:
                                status: done | superseded
                                retired: YYYY-MM-DD
                                superseded_by: <repo path>   (optional; must exist)
                                left_open: [...]             (optional)

The failure this exists for is the stale handoff: it reads exactly like a current one. So
`--check` fails on a missing or malformed block, a status in the wrong folder, an `open`
handoff nobody has touched in STALE_DAYS, a parked one that does not say what it waits on,
and any path to a handoff that no longer exists -- a retirement that moved a file and left
a pointer at its old address.

The index (no flag) writes nothing. Standard library only.
"""
import argparse
import datetime as dt
import glob
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# How long an `open` handoff may go without its `updated:` moving before --check fails.
# 14 is OUR number, picked as "two weeks of work moves an open stream or it is not open".
# TJ HAS NOT YET APPROVED IT; change it here, and only here, when he picks one.
STALE_DAYS = 14

LIVE_STATUSES = ('open', 'parked', 'reference')
RETIRED_STATUSES = ('done', 'superseded')

# A path to a handoff, live or retired, as prose or code would write it. The lookbehind
# keeps `notes/history/HANDOFF-x.md` and `foo/notes/HANDOFF-x.md` from matching as a
# shorter path; a glob (`HANDOFF-*.md`) or an ellipsis (`HANDOFF-…`) never matches at all.
HANDOFF_PATH = r'(?<![A-Za-z0-9_./-])notes/(?:handoffs-done/)?HANDOFF[A-Za-z0-9_.-]*\.md'

# Not scanned for dangling paths. Everything under these is either a document the archive
# manifest HASHES (sources/: page reads, published analyses) or a copy/output somebody else
# generates (fy28/public/ mirrors sources and the API; notes/generated/ is regenerated by its
# own scripts). A handoff path inside one of them is HISTORY -- what the document said when
# it was written -- and rewriting it would break the sha256 or be overwritten by the next
# run. CLAUDE.md says the same: retire a handoff and rewrite every pointer EXCEPT those.
SCAN_EXCLUDE = ('sources', 'fy28/public', 'notes/generated')


def parse_block(path):
    """The front-matter block as a dict, or None when the file does not open with one."""
    with open(path, encoding='utf-8') as f:
        lines = f.read().splitlines()
    if not lines or lines[0].strip() != '---':
        return None
    block = {}
    for line in lines[1:]:
        if line.strip() == '---':
            return block
        m = re.match(r'^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$', line)
        if not m:
            continue
        key, value = m.group(1), m.group(2)
        if value.startswith('['):
            # left_open: ["..."]  # a trailing comment -- keep the list, drop the comment
            end = value.rfind(']')
            value = value[:end + 1] if end >= 0 else value
        else:
            value = re.sub(r'\s+#\s.*$', '', value)
        block[key] = value.strip()
    return None   # opened with --- and never closed: not a block


def parse_date(value):
    try:
        return dt.date.fromisoformat(value)
    except (TypeError, ValueError):
        return None


def rel(root, path):
    return os.path.relpath(path, root)


def live_files(root):
    """Every notes/HANDOFF-*.md, plus each notes/PLAN-*.md that opens with a block."""
    files = sorted(glob.glob(os.path.join(root, 'notes', 'HANDOFF-*.md')))
    for plan in sorted(glob.glob(os.path.join(root, 'notes', 'PLAN-*.md'))):
        if parse_block(plan) is not None:
            files.append(plan)
    return files


def retired_files(root):
    return sorted(glob.glob(os.path.join(root, 'notes', 'handoffs-done', '*.md')))


def check_live(root, path, block, today):
    name = rel(root, path)
    if block is None:
        return [f'{name}: no status block (a `---` block opening the file)']
    out = []
    status = block.get('status', '')
    if status in RETIRED_STATUSES:
        out.append(f'{name}: status `{status}` outside notes/handoffs-done/ -- '
                   'retire it with git mv')
    elif status not in LIVE_STATUSES:
        out.append(f'{name}: status `{status}` is not one of {"|".join(LIVE_STATUSES)}')
    updated = parse_date(block.get('updated'))
    if updated is None:
        out.append(f'{name}: `updated:` missing or not YYYY-MM-DD '
                   f'({block.get("updated", "absent")!r})')
    elif status == 'open' and (today - updated).days > STALE_DAYS:
        out.append(f'{name}: open, and `updated: {updated}` is {(today - updated).days} '
                   f'days old (limit {STALE_DAYS}) -- update it, park it or retire it')
    # A handoff PORTED to genlock keeps its findings here and its next steps there: it says
    # `genlock: G-…` instead of `next:`, and must be `reference` (CLAUDE.md, Picking up).
    if block.get('genlock'):
        if status != 'reference':
            out.append(f'{name}: ported to genlock ({block["genlock"][:12]}) but `status: {status}`'
                       ' -- a ported handoff is `reference`; its state lives in genlock')
    elif not block.get('next'):
        out.append(f'{name}: `next:` missing (or `genlock: G-…` if its next steps were ported)')
    if status == 'parked' and not block.get('waiting_on'):
        out.append(f'{name}: parked without `waiting_on:`')
    return out


def check_retired(root, path, block):
    name = rel(root, path)
    if block is None:
        return [f'{name}: no status block (a `---` block opening the file)']
    out = []
    status = block.get('status', '')
    if status in LIVE_STATUSES:
        out.append(f'{name}: status `{status}` inside notes/handoffs-done/ -- '
                   'a live handoff belongs in notes/')
    elif status not in RETIRED_STATUSES:
        out.append(f'{name}: status `{status}` is not one of {"|".join(RETIRED_STATUSES)}')
    if parse_date(block.get('retired')) is None:
        out.append(f'{name}: `retired:` missing or not YYYY-MM-DD '
                   f'({block.get("retired", "absent")!r})')
    target = block.get('superseded_by')
    if target and not os.path.exists(os.path.join(root, target)):
        out.append(f'{name}: superseded_by `{target}` does not exist')
    return out


def dangling_paths(root):
    """Every handoff path named in a tracked file (outside SCAN_EXCLUDE) that is not there."""
    cmd = ['git', '-C', root, 'grep', '-n', '-o', '-P', HANDOFF_PATH, '--', '.']
    cmd += [f':(exclude){d}' for d in SCAN_EXCLUDE]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode not in (0, 1):   # 1 is "no match"; anything else is a broken scan
        raise SystemExit(f'git grep failed ({res.returncode}): {res.stderr.strip()}')
    out = []
    for line in res.stdout.splitlines():
        where_file, lineno, found = line.split(':', 2)
        if not os.path.exists(os.path.join(root, found)):
            out.append(f'{where_file}:{lineno}: names `{found}`, which does not exist')
    if res.returncode == 1 or not res.stdout:
        # A scan that matched nothing anywhere is a broken pattern, not a clean repo:
        # CLAUDE.md alone names several handoffs.
        out.append('dangling-path scan matched no handoff path in any tracked file -- '
                   'the pattern or the git grep is broken')
    return out


def collect_failures(root, today):
    failures = []
    for path in live_files(root):
        failures += check_live(root, path, parse_block(path), today)
    for path in retired_files(root):
        failures += check_retired(root, path, parse_block(path))
    failures += dangling_paths(root)
    return failures


def index(root, today):
    rows = []
    for path in live_files(root):
        block = parse_block(path) or {}
        updated = parse_date(block.get('updated'))
        age = (today - updated).days if updated else None
        rows.append((updated or dt.date.min, rel(root, path), block, age))
    rows.sort(key=lambda r: (r[0], r[1]))
    for _, name, block, age in rows:
        age_s = f'{age}d' if age is not None else '?d'
        line = (f'{block.get("status", "NO-BLOCK"):<9} {age_s:>4}  {name}  '
                f'next: {block.get("next") or ("genlock " + block["genlock"][:7] if block.get("genlock") else "-")}')
        if block.get('waiting_on'):
            line += f'  waiting_on: {block["waiting_on"]}'
        print(line)
    print(f'\n{len(rows)} live; {len(retired_files(root))} retired in notes/handoffs-done/')


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true',
                    help='exit 1 on any failure, naming each one')
    args = ap.parse_args(argv)
    today = dt.date.today()
    if not args.check:
        index(ROOT, today)
        return 0
    failures = collect_failures(ROOT, today)
    for f in failures:
        print(f'FAIL {f}')
    n_live, n_retired = len(live_files(ROOT)), len(retired_files(ROOT))
    if failures:
        print(f'\n{len(failures)} failure(s) across {n_live} live and {n_retired} retired handoffs')
        return 1
    print(f'ok: {n_live} live and {n_retired} retired handoffs; every block valid, '
          f'nothing open past {STALE_DAYS} days, no dangling handoff path')
    return 0


if __name__ == '__main__':
    sys.exit(main())
