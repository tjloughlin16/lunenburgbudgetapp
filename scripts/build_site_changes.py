#!/usr/bin/env python3
"""WHAT CHANGED, PER MENU ITEM -- the dates behind the indicators in the site menu.

TJ, 11 October 2026: *"We probably need indicators on the menu items to show changes."*

One small file the menu can fetch on every page, so it never loads the payloads themselves
(recording-minutes.json alone was 22 MB before it was split into an index and shards). For each menu item that has a dated record, a list
of CHANGES -- one per thing that moved, with the day it moved:

    jobs        a posting appeared, came down, or was relisted   job-postings.json history
    threads     a thread moved (its latest meeting)               threads.json last_moved
    recorded    our minutes of a recording were written           recording-minutes.json written.at
    budgetfeed  a budget item was put on the record               budget-feed.json entries
    boards      a board's meeting had new activity                meeting-feed.json recent
    reports     a report first appeared                           reports.json first_published

Dates only, never "today": the site counts what is new against the READER'S today and what
they have already seen, so the indicators decay without this file changing and the output
is reproducible (`--check`).

    python3 scripts/build_site_changes.py
    python3 scripts/build_site_changes.py --check
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'fy28', 'public', 'data')
OUT = os.path.join(DATA, 'site-changes.json')
KEEP = 200  # newest changes kept per item; past this the site prints "200+"


def load(name):
    with open(os.path.join(DATA, name), encoding='utf-8') as fh:
        return json.load(fh)


def newest(rows):
    seen, out = set(), []
    for d, i in sorted(rows, key=lambda r: (r[0], r[1]), reverse=True):
        if not d or (d, i) in seen:
            continue
        seen.add((d, i))
        out.append({'d': d[:10], 'id': i})
    return out[:KEEP]


def build():
    items = {}

    # Only what was DETECTED -- the same rule as the jobs tray: a posting already listed on an
    # employer's first check has no prev_look and is not a change anybody saw happen.
    items['jobs'] = newest(
        (e['date'], '%s:%s:%s' % (e['employer'], e['id'], e['event']))
        for e in load('job-postings.json')['history']
        if e.get('prev_look') and e.get('event') in ('posted', 'removed', 'relisted'))

    items['threads'] = newest((t.get('last_moved') or '', t['id']) for t in load('threads.json')['threads'])

    items['recorded'] = newest(
        ((m.get('written') or {}).get('at') or '', m['slug'])
        for m in load('recording-minutes.json')['meetings'])

    items['budgetfeed'] = newest(
        (e.get('date') or '', '%s:%s:%s' % (e.get('board_slug'), e.get('date'), (e.get('detail') or '')[:40]))
        for e in load('budget-feed.json')['entries'])

    items['boards'] = newest(
        (m.get('last_activity') or '', '%s:%s' % (m['board_slug'], m['date']))
        for m in load('meeting-feed.json')['recent']['meetings'])

    rep = load('reports.json')
    items['reports'] = newest((r.get('first_published') or '', r['url']) for r in rep['reports'] + rep['pages'])

    # A join that matches nothing looks exactly like nothing changing -- refuse instead.
    empty = [k for k, v in items.items() if not v]
    if empty:
        raise SystemExit('build_site_changes: no dated changes for %s -- a payload moved its '
                         'fields, or this read the wrong one' % ', '.join(empty))
    return {
        'about': 'Dated changes per site-menu item, newest first. The site counts those newer '
                 'than what the reader last saw, within a window from the reader\'s today. '
                 'Generated by scripts/build_site_changes.py.',
        'items': items,
    }


def main():
    fresh = json.dumps(build(), separators=(',', ':'))
    if '--check' in sys.argv:
        cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if cur != fresh:
            raise SystemExit('%s is stale. Run scripts/build_site_changes.py.' % os.path.relpath(OUT, ROOT))
        print('ok: %s' % os.path.relpath(OUT, ROOT))
        return
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write(fresh)
    d = json.loads(fresh)['items']
    print('wrote %s: %s' % (os.path.relpath(OUT, ROOT),
                            ', '.join('%s %d (newest %s)' % (k, len(v), v[0]['d']) for k, v in d.items())))


if __name__ == '__main__':
    main()
