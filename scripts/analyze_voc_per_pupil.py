#!/usr/bin/env python3
"""WHAT EVERY VOCATIONAL AND AGRICULTURAL DISTRICT SPENDS A PUPIL -- a quick analysis, not a
report. Writes notes/findings/VOC-TECH-PER-PUPIL.md.

    python3 scripts/analyze_voc_per_pupil.py

TJ, 14 October 2026, after the Monty Tech post: "Do we have the per pupil for all voc and
tech schools in the state? ... just do a quick analysis, not a full report yet (maybe stored
in an MD)". Every figure in the note is read here from DESE's district expenditures by
function workbook -- the `TTPP` row, "Expenditure (Admin, Instruction, Operations)", all
funds, the same row behind the $25,827 and $18,027 the site already cites. Nothing is typed.

WHICH DISTRICTS: those whose DESE name says Vocational, Agricultural or Technical. That is
a name filter, ours, and the note says so; a comprehensive district that runs vocational
programmes inside a high school is not in it, by construction.
"""
import collections
import os
import statistics

import openpyxl

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WB = os.path.join(ROOT, 'sources', 'state-dese', 'district-expenditures-by-function.xlsx')
OUT = os.path.join(ROOT, 'notes', 'findings', 'VOC-TECH-PER-PUPIL.md')
MONTY = '08320000'
LUNENBURG = '01620000'
KEYS = ('Vocational', 'Agricultural', 'Technical')


def read():
    """{(lea, name): {fy: (per_pupil, general, grants_revolving, total)}} for TTPP rows."""
    out = collections.defaultdict(dict)
    ws = openpyxl.load_workbook(WB, read_only=True)['Data']
    for r in ws.iter_rows(min_row=2, values_only=True):
        if r[3] != 'TTPP':
            continue
        name = str(r[2])
        if r[1] == LUNENBURG or any(k in name for k in KEYS):
            out[(r[1], name)][int(r[0])] = (r[11], r[8], r[9], r[10])
    return out


def usd(v):
    return '$' + format(round(v), ',')


def main():
    d = read()
    voc = {k: v for k, v in d.items() if k[0] != LUNENBURG}
    lun = next(v for k, v in d.items() if k[0] == LUNENBURG)
    years = sorted({y for v in voc.values() for y in v})
    last, prev = years[-1], years[-2]
    L = []
    w = L.append
    w('# Vocational and agricultural districts, per pupil')
    w('')
    w('*A quick analysis, not a report. Generated by `scripts/analyze_voc_per_pupil.py` from DESE\'s '
      '`district-expenditures-by-function.xlsx` (the `TTPP` row, "Expenditure (Admin, Instruction, '
      'Operations)", all funds, no capital or debt). Every figure is read, none typed.*')
    w('')
    ranks = {}
    for y in (last, prev):
        rows = sorted(((v[y][0], k) for k, v in voc.items() if y in v and v[y][0]), reverse=True)
        ranks[y] = rows
    for y in (last, prev):
        rows = ranks[y]
        pp = [p for p, _ in rows]
        pos = next(i for i, (_, k) in enumerate(rows, 1) if k[0] == MONTY)
        mpp = rows[pos - 1][0]
        w('## FY%d' % y)
        w('')
        w('- **%d districts.** Median %s a pupil; highest %s (%s); lowest %s (%s).'
          % (len(rows), usd(statistics.median(pp)), usd(rows[0][0]), rows[0][1][1],
             usd(rows[-1][0]), rows[-1][1][1]))
        w('- **Monty Tech: %s, %d of %d** (most spent first), %s below the median.'
          % (usd(mpp), pos, len(rows), usd(statistics.median(pp) - mpp)))
        if y in lun:
            w('- For scale, not comparison: Lunenburg Public Schools, a K-12 district, spent %s '
              'on the same row; that is below every district in this list.' % usd(lun[y][0])
              if lun[y][0] < rows[-1][0] else
              '- For scale, not comparison: Lunenburg Public Schools, a K-12 district, spent %s on the same row.' % usd(lun[y][0]))
        w('')
        w('| # | district | per pupil | from grants & revolving |')
        w('|---:|---|---:|---:|')
        for i, (p, k) in enumerate(rows, 1):
            g = voc[k][y]
            share = g[2] / g[3] if g[3] else 0
            name = '**%s**' % k[1] if k[0] == MONTY else k[1]
            w('| %d | %s | %s | %.1f%% |' % (i, name, usd(p), 100 * share))
        w('')
    # The district's own claim, tested.
    rows = ranks[prev]
    pos = next(i for i, (_, k) in enumerate(rows, 1) if k[0] == MONTY)
    w('## Monty Tech\'s own claim, tested')
    w('')
    w('Its FY27 budget presentation says that "in FY24, Monty Tech ranked 24th out of 28 in per '
      'pupil expenditures" among vocational and agricultural schools. On this list it is **%d of %d '
      'in FY%d**. The difference of one district is the list, not the figure: the presentation does '
      'not name its 28, and this list is a name filter of ours. Nothing here says which district it '
      'left out.' % (pos, len(rows), prev))
    w('')
    w('## What this does not show')
    w('')
    w('- **Why any district spends more.** Programme mix (shops differ in cost), size, the share of '
      'students with disabilities, and wages all move a per-pupil figure; nothing here separates them.')
    w('- **Comprehensive high schools with vocational programmes** are not in the list, by construction.')
    w('- **Capital and debt** are excluded for every district: the workbook has no such rows.')
    w('- **Dollars are nominal**, not adjusted for inflation.')
    w('')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
